// translate returns the Chinese form of s when lang is "zh", else s unchanged.
// Missing keys fall back to the English source so a new string never renders blank.
func translate(lang, s string) string {
	if lang == "zh" {
		if t, ok := zh[s]; ok {
			return t
		}
	}
	return s
}
