#!/usr/bin/env python3
# -*- coding: ascii -*-
"""CALDERA/stockpile chain importer (dev tool; NOT part of the qinjing runtime).

Adapts mitre/stockpile (Apache-2.0) linux sh abilities into the qinjing
proposal format, and composes multi-step chain buckets (G5). Reuses
import_art's hygiene rewrite / safe substitution / technique->signal mapping
so both importers share one hygiene contract. PyYAML is needed only to read
upstream ability files; the emitted proposal uses the frozen YAML subset.

The output is a PROPOSAL (proposals/), never merged into the frozen corpus by
this tool; merge_check + owner review decide adoption. The dedup gate
(tools/dedup.py) is advisory here: it reports skeleton/Jaccard overlap with
the current corpus so a reviewer sees near-duplicate risk before merging.

Usage:
    import_caldera.py <stockpile-root> --generate [--out proposals/caldera-import-r1.yaml]
    import_caldera.py <stockpile-root> --list

<stockpile-root> contains data/abilities/<tactic>/<uuid>.yml (a clone of
mitre/stockpile, or the offline fixture tests/fixture/caldera).
"""

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from parse import (cmd_hygiene_errors, parse_lines, validate,  # noqa: E402
                   parse_corpus, _write_targets)
from import_art import (hygiene_rewrite, substitute,  # noqa: E402
                        TECH_SIGNALS, _default_name)
from dedup import NearDupGate  # noqa: E402

try:
    import yaml
except ImportError:
    sys.stderr.write("PyYAML is required for this dev tool only "
                     "(pip install pyyaml); qinjing runtime stays "
                     "zero-dependency.\n")
    sys.exit(3)


# Curated linux abilities: (technique, name, signals, impact, mode, bin).
SELECTION = [
    ("T1082", "System Information Discovery", None, "none", "real", "uname"),
    ("T1018", "Remote System Discovery", None, "none", "real", "ip"),
    ("T1673", "Enumerate VMs", None, "none", "sim-missing-bin", "acrnctl"),
]

# Multi-step chains (G5): bucket -> ordered (technique, name) steps.
CHAINS = [
    ("chain-CAL1", [("T1082", "System Information Discovery"),
                    ("T1018", "Remote System Discovery")]),
]


def load_stockpile(root):
    index = {}
    base = os.path.join(root, "data", "abilities")
    for dirpath, _dirs, files in os.walk(base):
        for fn in sorted(files):
            if not fn.endswith((".yml", ".yaml")):
                continue
            with open(os.path.join(dirpath, fn), encoding="utf-8") as fh:
                doc = yaml.safe_load(fh)
            for ab in doc or []:
                tech = (ab.get("technique") or {}).get("attack_id", "")
                linux = (ab.get("platforms") or {}).get("linux") or {}
                sh = linux.get("sh") or {}
                command = sh.get("command") or ""
                if not tech or not command:
                    continue
                index[(tech, ab.get("name", ""))] = command
    return index


def adapt(tech, name, command, signals, impact, mode, bin_name):
    command = hygiene_rewrite(substitute(command, {}))
    command = "; ".join(l.strip() for l in command.strip().splitlines()
                        if l.strip())
    command = " ".join(command.split())
    tactic, sig = TECH_SIGNALS.get(tech, ("TA0002", ()))
    if signals is not None:
        sig = signals
    expect = "detectable" if sig else "gap"
    problems = cmd_hygiene_errors(command, impact)
    if problems:
        raise ValueError("%s hygiene: %s" % (tech, problems[0]))
    if not command.isascii():
        raise ValueError("%s: non-ASCII command" % tech)
    mkdirs = set(re.findall(r"mkdir(?:\s+-p)?\s+(/\S+)", command))
    cleanup = []
    for raw in _write_targets(command):
        t = raw.strip("'\"")
        if t.startswith("/tmp/qinjing-") and not t.endswith("/") \
                and t not in mkdirs and t not in cleanup:
            cleanup.append(t)
    return {"tech": tech, "tactic": tactic, "signals": list(sig),
            "expect": expect, "impact": impact, "cmd": command,
            "cleanup": ("rm -f " + " ".join(cleanup)) if cleanup else "",
            "mode": mode, "bin": bin_name, "name": _default_name(name),
            "creates_process": True}


def serialize(cases, chain_of):
    lines = ["# Generated by tools/import_caldera.py from mitre/stockpile",
             "# (Apache-2.0). Proposal only; merge_check + review decide.",
             "", "false_positives:", "", "attacks:"]
    for seq, c in enumerate(cases, 1):
        lines.extend([
            "  - id: CAL%02d" % seq,
            "    tactic: %s" % c["tactic"],
            "    technique: %s" % c["tech"],
            "    name: '%s'" % c["name"].replace("'", "''"),
            "    platforms: [linux]",
            "    cmd: '%s'" % c["cmd"].replace("'", "''"),
            "    bin: '%s'" % c["bin"],
            "    creates_process: true",
            "    mode: %s" % c["mode"],
            "    expected_signals: [%s]" % ", ".join(c["signals"]),
            "    related_signals: []",
            "    expect: %s" % c["expect"],
            "    impact: %s" % c["impact"],
        ])
        if c["cleanup"]:
            lines.append("    cleanup: %s" % c["cleanup"])
        if c["tech"] in chain_of:
            lines.append("    bucket: %s" % chain_of[c["tech"]])
    return "\n".join(lines) + "\n"


def main(argv):
    if len(argv) < 3:
        sys.stderr.write(__doc__)
        return 2
    root, mode = argv[1], argv[2]
    index = load_stockpile(root)
    if mode == "--list":
        for (tech, name), cmd in sorted(index.items()):
            print("%s | %-40s | %s" % (tech, name[:40],
                                       " ".join(cmd.split())[:80]))
        print("# %d linux sh abilities indexed" % len(index))
        return 0
    if mode != "--generate":
        sys.stderr.write(__doc__)
        return 2
    rest = argv[3:]
    if rest and rest[0] == "--out":
        out_path = rest[1]
    elif rest:
        out_path = rest[0]
    else:
        out_path = os.path.join(
            os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
            "proposals", "caldera-import-r1.yaml")
    chain_of = {}
    for bucket, steps in CHAINS:
        for tech, _n in steps:
            chain_of[tech] = bucket
    cases, rejects = [], []
    for tech, name, sig, impact, mode_, bin_name in SELECTION:
        cmd = index.get((tech, name))
        if cmd is None:
            rejects.append("%s %r not in stockpile index" % (tech, name))
            continue
        try:
            cases.append(adapt(tech, name, cmd, sig, impact, mode_, bin_name))
        except ValueError as exc:
            rejects.append(str(exc))
    text = serialize(cases, chain_of)
    problems = validate(parse_lines(text.splitlines()))
    if problems:
        for p in problems:
            sys.stderr.write("INVALID: %s\n" % p)
        return 1
    # Advisory dedup vs the frozen corpus (reviewer sees near-dup risk).
    repo = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    corpus = parse_corpus(os.path.join(repo, "corpus", "qinjing.yaml"))
    gate = NearDupGate(corpus["false_positives"] + corpus["attacks"])
    overlap = 0
    for c in cases:
        klass = c["signals"][0] if c["signals"] else "(gap)"
        if gate.check(c["cmd"], klass):
            overlap += 1
    with open(out_path, "w", encoding="ascii", newline="\n") as fh:
        fh.write(text)
    mapped = sum(1 for c in cases if c["expect"] == "detectable")
    print("generated %d cases (%d detectable, %d gap), %d chain steps, "
          "%d near-dup overlap -> %s"
          % (len(cases), mapped, len(cases) - mapped, len(chain_of),
             overlap, out_path))
    for r in rejects:
        sys.stderr.write("REJECT: %s\n" % r)
    return 1 if rejects else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))