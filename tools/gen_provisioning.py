#!/usr/bin/env python
# -*- coding: ascii -*-
"""Provisioning manifest generator (docs/11 T5).

Derives data/provisioning.tsv from the corpus: per signal class, the
cases, the distinct required binaries (the runner probes them with
`command -v`; bin '-' means shell builtin, nothing to probe), how many
cases are sim-missing-bin, whether the class is sim-only, whether the
class is evaluable on the reference bench, and whether any case needs a
reachable remote peer or listener (service dependency, counted apart
from the bin criterion). Regenerate after any corpus change:

    gen_provisioning.py [--out data/provisioning.tsv] [corpus.yaml]

Stdout reports the two disclosure numbers (docs/11 T5): corpus-level
class count vs classes effectively evaluable on the reference bench.
"Reference bench" follows the corpus mode convention: real means the bin
ships with the reference minimal image, sim-missing-bin means it does
not, so a class is evaluable there exactly when none of its cases is
sim-missing-bin.
"""

import argparse
import hashlib
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REGISTRY = os.path.join(ROOT, "data", "family-registry.tsv")

sys.path.insert(0, os.path.join(ROOT, "tools"))
from parse import parse_corpus, SIGNAL_CLASSES  # noqa: E402

# CentOS-7 style package names for bins whose package differs from the
# command; every other provisioning-gap bin falls back to its own name.
BIN_PACKAGES = {
    "ssh": "openssh-clients", "scp": "openssh-clients",
    "sftp": "openssh-clients", "dig": "bind-utils",
    "mysql": "mariadb", "mysqldump": "mariadb",
    "psql": "postgresql", "pg_basebackup": "postgresql",
    "redis-cli": "redis", "iostat": "sysstat",
    "kubectl": "kubectl (upstream binary)", "mongosh": "mongodb-org-shell",
    "nmap": "nmap (EPEL)", "sshpass": "sshpass (EPEL)",
    "code": "code cli (upstream)",
}

# A case depends on a reachable remote peer/listener when its cmd aims
# at a remote endpoint: user@host forms, scheme URLs to TEST-NET or the
# metadata address, host:port and "host port" pairs on TEST-NET, -h
# service flags, and dns @server forms. Bare unroutable-TEST-NET scan
# targets still execute (finding nothing), so they stay out.
REMOTE_ENDPOINT_RE = re.compile(
    r"@[\w.-]*203\.0\.113\.|@[\w.-]*127\.0\.0\.1\b"
    r"|://203\.0\.113\.|://169\.254\.169\.254"
    r"|[\s/]203\.0\.113\.\d+:\d+|\s203\.0\.113\.\d+\s+\d{2,5}\b"
    r"|-h 203\.0\.113\.|-h 169\.254\.169\.254|@203\.0\.113\.\d+\b")


def load_class_membership():
    membership = {}
    for line in open(REGISTRY, encoding="ascii"):
        if line.startswith("#") or not line.strip():
            continue
        parts = line.rstrip("\n").split("\t")
        if len(parts) >= 3:
            membership.setdefault(parts[1], []).append(parts[0])
    return membership


def build_rows(cases, membership):
    by_id = {}
    for section in ("false_positives", "attacks"):
        for case in cases[section]:
            by_id[case["id"]] = case
    rows = []
    for klass in sorted(SIGNAL_CLASSES):
        members = [by_id[cid] for cid in membership.get(klass, [])
                   if cid in by_id]
        bins = sorted({c["bin"] for c in members
                       if c.get("bin") not in ("-", "", None)})
        sim_missing = sum(1 for c in members
                          if c.get("mode") == "sim-missing-bin")
        sim_only = "yes" if members and sim_missing == len(members) else "no"
        evaluable = "yes" if members and sim_missing == 0 else "no"
        # Provisioning gap: the bins carried by sim-missing-bin cases -
        # exactly what a bare reference bench must install (plus any
        # service dependency) to make the class evaluable there.
        gap = sorted({c["bin"] for c in members
                      if c.get("mode") == "sim-missing-bin"
                      and c.get("bin") not in ("-", "", None)})
        cmds = " | ".join(c.get("cmd", "") for c in members)
        service = "yes" if REMOTE_ENDPOINT_RE.search(cmds) else "no"
        install = ", ".join(BIN_PACKAGES.get(b, b) for b in gap)
        rows.append({
            "class": klass, "cases": len(members), "bins": ",".join(bins),
            "sim_missing": sim_missing, "sim_only": sim_only,
            "evaluable": evaluable, "service": service,
            "install": install or "-",
        })
    return rows


def render(rows, corpus_sha):
    out = [
        "# provisioning manifest for the qinjing corpus (docs/11 T5)",
        "# generated by tools/gen_provisioning.py - regenerate, do not"
        " hand-edit",
        "# corpus sha256: %s" % corpus_sha,
        "# columns: class, cases, bins, sim_missing, sim_only,"
        " evaluable_ref, service_dep, install_hint",
        "# evaluable_ref: every case's bin present on the reference bench"
        " (mode convention,",
        "#   same criterion the runner applies with `command -v`);"
        " service_dep classes",
        "#   additionally need a reachable remote peer or listener and are"
        " never",
        "#   counted through the bin criterion. install_hint lists the"
        " provisioning",
        "#   gap (bins carried by sim-missing-bin cases, CentOS-7 package"
        " names).",
        "# gap-labelled and benign cases sit outside the 52-class table"
        " (their",
        "#   families carry no signal class).",
    ]
    for r in rows:
        out.append("\t".join([
            r["class"], str(r["cases"]), r["bins"] or "-",
            str(r["sim_missing"]), r["sim_only"], r["evaluable"],
            r["service"], r["install"]]))
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description="provisioning manifest")
    ap.add_argument("corpus", nargs="?", default=os.path.join(
        ROOT, "corpus", "qinjing.yaml"))
    ap.add_argument("--out", default=os.path.join(
        ROOT, "data", "provisioning.tsv"))
    args = ap.parse_args(argv)

    cases = parse_corpus(args.corpus)
    with open(args.corpus, "rb") as fh:
        corpus_sha = hashlib.sha256(fh.read()).hexdigest()
    rows = build_rows(cases, load_class_membership())
    text = render(rows, corpus_sha)
    with open(args.out, "w", encoding="ascii", newline="\n") as fh:
        fh.write(text)

    total = len(rows)
    evaluable = sum(1 for r in rows if r["evaluable"] == "yes")
    service = sum(1 for r in rows if r["service"] == "yes")
    sim_only = [r["class"] for r in rows if r["sim_only"] == "yes"]
    print("classes (corpus-level): %d" % total)
    print("evaluable on reference bench: %d classes" % evaluable)
    print("service-dependent classes: %d (need a reachable peer;"
          " counted separately from the bin criterion)" % service)
    print("sim-only classes: %d (%s)" % (len(sim_only), ", ".join(sim_only)))
    print("wrote %s (%d rows)" % (args.out, total))
    return 0


if __name__ == "__main__":
    sys.exit(main())
