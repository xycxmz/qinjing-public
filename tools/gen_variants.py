def yaml_escape(text):
    return text.replace("'", "''")


def generate(corpus_path, output_path, count_per_class, only_classes=None,
             interleave=False):
    cases = parse_corpus(corpus_path)
    existing_cmds = set()
    for section in ("false_positives", "attacks"):
        for case in cases[section]:
            existing_cmds.add(case.get("cmd", ""))

    classes = only_classes or CLASS_ORDER
    # Continue VR numbering after the highest existing variant ID.
    import re as _re
    seq = 0
    for section in ("false_positives", "attacks"):
        for case in cases[section]:
            m = _re.match(r"VR(\d+)", case.get("id", ""))
            if m:
                seq = max(seq, int(m.group(1)))
    per_class = {}
    skipped_dupe = 0
    skipped_hygiene = 0

    for class_name in classes:
        if class_name not in SHAPES:
            print("WARNING: no shapes for %s" % class_name)
            continue
        spec = SHAPES[class_name]
        bucket = per_class.setdefault(class_name, [])
        count = 0
        for entry in spec["entries"]:
            cmd, impact, mode, bin_name = entry[0], entry[1], entry[2], entry[3]
            cleanup = entry[4] if len(entry) > 4 else None
            if count >= count_per_class:
                break
            if cmd in existing_cmds:
                skipped_dupe += 1
                continue
            problems = cmd_hygiene_errors(cmd, impact)
            if problems:
                skipped_hygiene += 1
                print("HYGIENE REJECT [%s]: %s -> %s" % (class_name, cmd[:50], problems[0]))
                continue
            seq += 1
            count += 1
            bucket.append({
                "id": "VR%03d" % seq, "tactic": spec["tactic"],
                "technique": spec["technique"],
                "name": class_name + " variant " + str(count),
                "platforms": ["linux"],
                "cmd": "'" + yaml_escape(cmd) + "'",
                "bin": "'" + bin_name + "'",
                "creates_process": "true" if mode != "sim-builtin" else "false",
                "mode": mode,
                "expected_signals": "[" + class_name + "]",
                "related_signals": "[]",
                "expect": "detectable",
                "impact": impact,
                "cleanup": cleanup,
            })

    # Execution order is file order, so same-class cases must not sit
    # adjacent; --interleave round-robins across classes (lesson 3).
    ordered = []
    if interleave:
        queues = [per_class[c] for c in classes if per_class.get(c)]
        while any(queues):
            for queue in queues:
                if queue:
                    ordered.append(queue.pop(0))
    else:
        for class_name in classes:
            ordered.extend(per_class.get(class_name, []))

    lines = ["# Generated by tools/gen_variants.py", "# Do not edit by hand; regenerate with different --count-per-class.", ""]
    lines.append("false_positives:")
    lines.append("")
    lines.append("attacks:")
    for entry in ordered:
        lines.append("  - id: " + entry["id"])
        for key in ("tactic", "technique", "name", "platforms", "cmd", "bin",
                    "creates_process", "mode", "expected_signals",
                    "related_signals", "expect", "impact"):
            lines.append("    %s: %s" % (key, entry[key]))
        if entry["cleanup"]:
            lines.append("    cleanup: " + entry["cleanup"])
    text = "\n".join(lines) + "\n"

    with open(output_path, "w", encoding="ascii", newline="\n") as fh:
        fh.write(text)
    print("generated %d cases (%d skipped as duplicates, %d failed hygiene)"
          % (len(ordered), skipped_dupe, skipped_hygiene))
    print("wrote %s" % output_path)
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description="variant generator")
    ap.add_argument("corpus")
    ap.add_argument("--output", required=True)
    ap.add_argument("--count-per-class", type=int, default=25)
    ap.add_argument("--classes", default=None,
                    help="comma-separated class names (default: all)")
    ap.add_argument("--interleave", action="store_true",
                    help="round-robin across classes so same-class cases"
                         " are not adjacent (execution order = file order)")
    args = ap.parse_args(argv)
    only = [c.strip() for c in args.classes.split(",")] if args.classes else None
    return generate(args.corpus, args.output, args.count_per_class, only,
                    args.interleave)


